// Copies the Gno contracts into the TypeScript core so the UI and MCP server
// can show and audit the exact same source when a package is not on chain yet.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const contracts = join(root, "contracts");
const out = join(root, "packages/core/src/bundled-sources.ts");

const pkgs = {};
function walk(dir) {
  const entries = readdirSync(dir);
  if (entries.includes("gnomod.toml")) {
    const mod = readFileSync(join(dir, "gnomod.toml"), "utf8").match(/module\s*=\s*"([^"]+)"/);
    if (!mod) throw new Error(`no module in ${dir}/gnomod.toml`);
    pkgs[mod[1]] = entries
      .filter((f) => f.endsWith(".gno") || f === "gnomod.toml")
      .sort()
      .map((name) => ({ name, body: readFileSync(join(dir, name), "utf8") }));
  }
  for (const e of entries) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p);
  }
}
walk(contracts);

const body =
  "// Generated by scripts/sync-sources.mjs from contracts/. Do not edit.\n" +
  'import type { SourceFile } from "./types";\n\n' +
  "export const BUNDLED_SOURCES: Record<string, SourceFile[]> = " +
  JSON.stringify(pkgs, null, 2) +
  ";\n";
writeFileSync(out, body);
console.log(`synced ${Object.keys(pkgs).length} packages -> ${relative(root, out)}`);
